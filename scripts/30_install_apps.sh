#!/usr/bin/env bash
# Install the application services (Python API, Streamlit, Node API, Next.js
# RAG) as systemd services, plus JupyterLab.
#
# Assumes: 20_install_native.sh and 15_install_node.sh / 15_install_python.sh
# have already been run.
set -euo pipefail

REPO_DIR="${REPO_DIR:-/opt/mlops-webshop-stack}"
APPS_DIR=/opt/apps
ROOT_ENV="${ROOT_ENV:-$REPO_DIR/.env}"

if [[ $EUID -ne 0 ]]; then
  echo "run as root" >&2
  exit 1
fi

# --- Load the operator's secrets from the root .env --------------------------
# The app .env files MUST carry the REAL secrets, not the placeholders from
# the .env.example templates.
#
# The previous version only did `cp .env.example .env`, which produced
# `JWT_SECRET=change_me_jwt_secret` in /opt/apps/python-api/.env. The API
# refuses to start with a placeholder JWT_SECRET (Pydantic validator), so
# the documented deploy path produced a service that could never boot.
#
# The root .env is the single source of truth; it is rendered into each
# app's .env below. Existing app .env files are BACKED UP, not silently
# overwritten, so a hand-tuned config is never lost.
if [[ ! -f "$ROOT_ENV" ]]; then
  echo "ERROR: $ROOT_ENV not found." >&2
  echo "       Create it first: cp $REPO_DIR/.env.example $ROOT_ENV" >&2
  echo "       then set every secret in it and re-run this script." >&2
  exit 1
fi

set -a
# shellcheck disable=SC1090
source "$ROOT_ENV"
set +a

# Fail fast rather than deploying an API that cannot start.
: "${JWT_SECRET:?JWT_SECRET is not set in $ROOT_ENV}"
: "${POSTGRES_PASSWORD:?POSTGRES_PASSWORD is not set in $ROOT_ENV}"
: "${POSTGRES_USER:?POSTGRES_USER is not set in $ROOT_ENV}"
: "${POSTGRES_DB:?POSTGRES_DB is not set in $ROOT_ENV}"

# ANON_SALT has no default: generate one on first run and persist it to
# the root .env so the anonymous visitor tokens stay stable across
# redeploys (rotating it de-links the historical anonymous data).
if [[ -z "${ANON_SALT:-}" || "$ANON_SALT" == "change_me_anon_salt" ]]; then
  ANON_SALT="$(openssl rand -hex 32)"
  echo "[apps] generated a new ANON_SALT (persisted to $ROOT_ENV)"
  if grep -q '^ANON_SALT=' "$ROOT_ENV"; then
    sed -i "s|^ANON_SALT=.*|ANON_SALT=${ANON_SALT}|" "$ROOT_ENV"
  else
    printf '\n# Generated by 30_install_apps.sh on first run\nANON_SALT=%s\n' \
      "$ANON_SALT" >> "$ROOT_ENV"
  fi
fi

# The API's DSN must carry the real database password.
APP_DATABASE_URL="postgresql+psycopg://${POSTGRES_USER}:${POSTGRES_PASSWORD}@${POSTGRES_HOST:-127.0.0.1}:${POSTGRES_PORT:-5432}/${POSTGRES_DB}"

# write_app_env <target-path> <<'EOF' ... EOF
# Writes stdin to the target, backing up any previous version.
write_app_env() {
  local target="$1" tmp
  tmp="$(mktemp)"
  cat > "$tmp"
  if [[ -f "$target" ]] && ! cmp -s "$tmp" "$target"; then
    cp "$target" "${target}.bak.$(date +%Y%m%d-%H%M%S)"
  fi
  install -m 640 "$tmp" "$target"
  rm -f "$tmp"
}

# --- Preflight: the toolchain must be new enough ---------------------------
command -v node >/dev/null || { echo "node missing — run 15_install_node.sh" >&2; exit 1; }
command -v python3.11 >/dev/null || { echo "python3.11 missing — run 15_install_python.sh" >&2; exit 1; }
node -e 'const m=+process.versions.node.split(".")[0]; if(m<18){console.error("node "+process.versions.node+" is too old, need >=18.17");process.exit(1)}'
echo "[apps] toolchain: $(node --version), $(python3.11 --version)"

mkdir -p "$APPS_DIR"

# --- Python API -------------------------------------------------------------
echo "[apps] python-api"
rsync -a --delete \
  --exclude '.venv' --exclude '.env' --exclude '__pycache__' --exclude '.next' \
  "$REPO_DIR/apps/python-api/" "$APPS_DIR/python-api/"
cd "$APPS_DIR/python-api"
python3.11 -m venv .venv
.venv/bin/pip install --upgrade pip setuptools wheel
.venv/bin/pip install -r requirements.txt
# Render the REAL secrets into the app .env. A placeholder JWT_SECRET here
# means the API refuses to start.
write_app_env "$APPS_DIR/python-api/.env" <<EOF
# Generated by 30_install_apps.sh — do not edit by hand.
# Edit $ROOT_ENV and re-run the script instead.
DATABASE_URL=${APP_DATABASE_URL}
ENVIRONMENT=${ENVIRONMENT:-production}
JWT_SECRET=${JWT_SECRET}
JWT_ALGORITHM=HS256
ACCESS_TOKEN_TTL_MINUTES=${ACCESS_TOKEN_TTL_MINUTES:-720}
REFRESH_TOKEN_TTL_DAYS=${REFRESH_TOKEN_TTL_DAYS:-30}
CORS_ORIGINS=${CORS_ORIGINS:-}
METRICS_ENABLED=${METRICS_ENABLED:-true}
METRICS_PATH=/metrics
ANON_SALT=${ANON_SALT}
ALLOWED_HOSTS=${ALLOWED_HOSTS:-}
EOF

# --- Streamlit --------------------------------------------------------------
echo "[apps] streamlit-app"
rsync -a --delete \
  --exclude '.venv' --exclude '.env' --exclude '__pycache__' \
  "$REPO_DIR/apps/streamlit-app/" "$APPS_DIR/streamlit-app/"
cd "$APPS_DIR/streamlit-app"
python3.11 -m venv .venv
.venv/bin/pip install --upgrade pip setuptools wheel
.venv/bin/pip install -r requirements.txt
write_app_env "$APPS_DIR/streamlit-app/.env" <<EOF
# Generated by 30_install_apps.sh — do not edit by hand.
API_BASE=http://127.0.0.1:3000
CURRENCY_SYMBOL=${CURRENCY_SYMBOL:-€}
EOF

# --- Node API ---------------------------------------------------------------
echo "[apps] node-api"
rsync -a --delete \
  --exclude 'node_modules' --exclude '.env' \
  "$REPO_DIR/apps/node-api/" "$APPS_DIR/node-api/"
cd "$APPS_DIR/node-api"
# `npm ci` REQUIRES package-lock.json and fails without it. The lockfiles are
# committed to the repository; if one is missing the build is broken.
if [[ ! -f package-lock.json ]]; then
  echo "ERROR: apps/node-api/package-lock.json is missing (npm ci will fail)" >&2
  exit 1
fi
npm ci --omit=dev --no-audit --no-fund
write_app_env "$APPS_DIR/node-api/.env" <<EOF
# Generated by 30_install_apps.sh — do not edit by hand.
OLLAMA_URL=${OLLAMA_URL:-http://127.0.0.1:11434}
OLLAMA_MODEL=${OLLAMA_MODEL:-qwen2.5:0.5b}
OLLAMA_TIMEOUT_MS=${OLLAMA_TIMEOUT_MS:-300000}
PORT=8000
HOST=127.0.0.1
DATABASE_URL=postgres://${POSTGRES_USER}:${POSTGRES_PASSWORD}@${POSTGRES_HOST:-127.0.0.1}:${POSTGRES_PORT:-5432}/${POSTGRES_DB}
LOG_LEVEL=info
EOF

# --- Next.js RAG ------------------------------------------------------------
echo "[apps] nextjs-rag"
rsync -a --delete \
  --exclude 'node_modules' --exclude '.next' --exclude '.env' \
  "$REPO_DIR/apps/nextjs-rag/" "$APPS_DIR/nextjs-rag/"
cd "$APPS_DIR/nextjs-rag"
if [[ ! -f package-lock.json ]]; then
  echo "ERROR: apps/nextjs-rag/package-lock.json is missing (npm ci will fail)" >&2
  exit 1
fi
npm ci --no-audit --no-fund
npm run build
write_app_env "$APPS_DIR/nextjs-rag/.env" <<EOF
# Generated by 30_install_apps.sh — do not edit by hand.
OLLAMA_URL=${OLLAMA_URL:-http://127.0.0.1:11434}
OLLAMA_MODEL=${OLLAMA_MODEL:-qwen2.5:0.5b}
OLLAMA_TIMEOUT_MS=${OLLAMA_TIMEOUT_MS:-300000}
RAG_PORT=8001
EOF

# --- JupyterLab -------------------------------------------------------------
echo "[apps] jupyterlab"
id -u jupyter >/dev/null 2>&1 || useradd -m -s /bin/bash jupyter
mkdir -p /opt/jupyter
python3.11 -m venv /opt/jupyter/.venv
/opt/jupyter/.venv/bin/pip install --upgrade pip setuptools wheel
/opt/jupyter/.venv/bin/pip install jupyterlab
chown -R jupyter:jupyter /opt/jupyter /home/jupyter

# A Jupyter token is mandatory. Generate one if the operator did not.
if [[ ! -f /opt/jupyter/.env ]]; then
  JUPYTER_TOKEN="$(openssl rand -hex 32)"
  cat > /opt/jupyter/.env <<EOF
# JupyterLab access token. Treat as a credential: anyone with it can execute
# arbitrary code on this host.
JUPYTER_TOKEN=${JUPYTER_TOKEN}
EOF
  chmod 600 /opt/jupyter/.env
  echo "[apps] jupyter token generated — read it from /opt/jupyter/.env"
fi
chown jupyter:jupyter /opt/jupyter/.env
chmod 600 /opt/jupyter/.env

# --- Ownership --------------------------------------------------------------
chown -R www-data:www-data "$APPS_DIR"

# --- systemd units ----------------------------------------------------------
for unit in python-api streamlit-app node-api nextjs-rag jupyterlab; do
  install -m 644 "$REPO_DIR/systemd/${unit}.service" /etc/systemd/system/
done
systemctl daemon-reload

# --- Start (but do not fail the script on a unit that needs manual setup) ---
for unit in python-api streamlit-app node-api nextjs-rag jupyterlab; do
  systemctl enable --now "$unit" || echo "[apps] WARNING: $unit failed to start — check: journalctl -u $unit" >&2
done

echo "[apps] done"
